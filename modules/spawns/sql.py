"""The server side of a generated zone's monsters, as one SQL file (a server module).

Per monster type: a mob pool cloned from a real one (its fight, family, skills) with our model and a
hitbox scaled to match; a mob group in the zone (levels, respawn, drops); spawn points from spawns.py.
Deletes before inserting, so it can be re-run.

Mob ids: 0x1000000 + (zone << 12) + n. FFXI positions: x east, y down, z north.
"""
import math
import struct


def modelid_blob(model_id):
    return "0x" + (struct.pack("<HH", 0, model_id) + bytes(16)).hex().upper()


def write_sql(path, zone_id, mobs_spec, placements, source_json):
    types = mobs_spec["types"]
    pools_from = mobs_spec["pools_from"]
    mob_base = 0x1000000 + (zone_id << 12)
    lines = [f"-- Monsters for zone {zone_id}: generated by LPS caves from {source_json}. Do not edit by hand.",
             f"-- Models {mobs_spec['models_from']}+ are built into the client by the same run (LPS mobs recolour).",
             "",
             f"DELETE FROM `mob_spawn_points` WHERE `mobid` BETWEEN {mob_base + 1} AND {mob_base + 4095};",
             f"DELETE FROM `mob_groups` WHERE `zoneid` = {zone_id};",
             f"DELETE FROM `mob_pools` WHERE `poolid` BETWEEN {pools_from} AND {pools_from + 99};",
             ""]
    group_of = {}
    for i, (key, t) in enumerate(types.items()):
        pool = pools_from + i
        group = i + 1
        group_of[key] = group
        name = t["name"]
        scale = t.get("model", {}).get("scale", 1.0)
        lines += [f"-- {key}: {name}, from pool {t['pool']}, model {t.get('model_id') or 'the pool\'s own'}",
                  "DROP TEMPORARY TABLE IF EXISTS tmp_pool;",
                  f"CREATE TEMPORARY TABLE tmp_pool AS SELECT * FROM `mob_pools` WHERE `poolid` = {t['pool']};",
                  f"UPDATE tmp_pool SET `poolid` = {pool}, `name` = '{name}', `packet_name` = '{name}', "
                  + (f"`modelid` = {modelid_blob(t['model_id'])}, " if t.get("model_id") else "")
                  + f"`modelHitboxSize` = LEAST(ROUND(IFNULL(`modelHitboxSize`, 4) * {scale:.2f}), 255);",
                  "INSERT INTO `mob_pools` SELECT * FROM tmp_pool;"]
        lo, hi = (t["level"], t["level"]) if isinstance(t["level"], int) else t["level"]
        lines.append(f"INSERT INTO `mob_groups` VALUES ({group},{pool},{zone_id},'{name}',{t.get('respawn', 600)},"
                     f"{t.get('spawntype', 0)},{t.get('drop', 0)},{t.get('hp', 0)},0,{lo},{hi},0);")
        lines.append("")
    lines.append("DROP TEMPORARY TABLE IF EXISTS tmp_pool;")
    lines.append("")
    for n, p in enumerate(placements, 1):
        t = types[p["type"]]
        x, y, z = p["pos"]
        rot = int(round(-p["facing"] * 128 / math.pi)) & 0xFF
        lines.append(f"INSERT INTO `mob_spawn_points` VALUES ({mob_base + n},0,'{t['name']}','{t['name']}',"
                     f"{group_of[p['type']]},{x:.3f},{-z:.3f},{y:.3f},{rot});")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return len(placements)
